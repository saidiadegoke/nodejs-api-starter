import {
  Body,
  Controller,
  Delete,
  Get,
  HttpCode,
  HttpStatus,
  Param,
  Post,
  UseGuards,
} from '@nestjs/common';
import {
  ApiTags,
  ApiOperation,
  ApiOkResponse,
  ApiCreatedResponse,
  ApiBearerAuth,
  ApiParam,
} from '@nestjs/swagger';
import { JwtAuthGuard, CurrentUser } from '../../../shared';
import { ApiKeysService } from '../services/api-keys.service';
import { CreateApiKeyDto } from '../dto/create-api-key.dto';
import { ApiKeyIdParamDto } from '../dto/api-key-id-param.dto';

@ApiTags('API Keys')
@Controller('api-keys')
@UseGuards(JwtAuthGuard)
@ApiBearerAuth('JWT-auth')
export class ApiKeysController {
  constructor(private readonly apiKeysService: ApiKeysService) {}

  @Post()
  @HttpCode(HttpStatus.CREATED)
  @ApiOperation({
    summary: 'Generate a new API key',
    description: 'Generates a secure API key with the prefix and stores the hashed token. The full raw key is shown only once.',
  })
  @ApiCreatedResponse({ description: 'API key created successfully' })
  async generate(
    @CurrentUser('user_id') userId: string,
    @Body() dto: CreateApiKeyDto,
  ) {
    const key = await this.apiKeysService.generate(userId, dto.name);
    return {
      message: 'API key created successfully. Store the key securely — it will not be shown again.',
      data: key,
    };
  }

  @Get()
  @ApiOperation({
    summary: 'List user API keys',
    description: 'Returns all active and revoked API keys generated by the authenticated user with masked tokens.',
  })
  @ApiOkResponse({ description: 'API keys retrieved successfully' })
  async list(@CurrentUser('user_id') userId: string) {
    const keys = await this.apiKeysService.list(userId);
    return {
      message: 'API keys retrieved successfully',
      data: keys,
    };
  }

  @Delete(':id')
  @ApiOperation({
    summary: 'Revoke an API key',
    description: 'Immediately revokes an active API key belonging to the authenticated user.',
  })
  @ApiParam({ name: 'id', description: 'API key UUID' })
  @ApiOkResponse({ description: 'API key revoked successfully' })
  async revoke(
    @CurrentUser('user_id') userId: string,
    @Param() params: ApiKeyIdParamDto,
  ) {
    const key = await this.apiKeysService.revoke(params.id, userId);
    return {
      message: 'API key revoked successfully',
      data: key,
    };
  }
}
